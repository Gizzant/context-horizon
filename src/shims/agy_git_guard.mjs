import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

/**
 * DET-19: Git Hook-Bypass Guard Shim (`src/shims/agy_git_guard.mjs`)
 *
 * Intercepts `git` invocations and strictly blocks evasion flags:
 *  - `git commit` with `--no-verify`, standalone `-n`, grouped `-amn` / `-cn`, or `--no-gpg-sign`.
 *  - `git push`, `git merge`, `git rebase`, `git cherry-pick` with `--no-verify`.
 *  - Global config overrides: `-c core.hooksPath=...` (e.g. `/dev/null` or `NUL`).
 *  - Child environment overrides: `HUSKY=0` or `GIT_HOOKS=0`.
 *
 * Subcommand-Aware (Zero False Positives):
 *  - Does NOT block legitimate flags like `git log -n 5`, `git clean -n`, or `git diff --name-only`.
 *
 * Anti-Gaming Human Override:
 *  - Prohibits static env flags like `HORIZON_BYPASS=1`.
 *  - Permits bypass ONLY via a one-time cryptographic nonce generated by an explicit
 *    VS Code command with a 60-second TTL (`.agents/cache/git_bypass_nonce.json`).
 */

export const DET19_CONSTANTS = Object.freeze({
  DETECTOR_ID: 'DET-19',
  EXIT_CODE_BLOCKED: 126,
  BLOCKED_MESSAGE:
    '[HORIZON DET-19 BLOCKED] Pre-commit / verification bypass flags (--no-verify, -n, hooksPath override) are prohibited. Read the hook failure output and fix the underlying lint, type, or test error.',
  BYPASS_NONCE_TTL_MS: 60000,
  PROTECTED_SUBCOMMANDS: Object.freeze(['commit', 'push', 'merge', 'rebase', 'cherry-pick'])
});

/**
 * Resolves the real system git binary while filtering out `.agents/shims` to avoid infinite recursion.
 */
export function resolveRealGitBinary({
  env = process.env,
  platform = process.platform,
  fsModule = fs
} = {}) {
  const pathSeparator = platform === 'win32' ? ';' : ':';
  const pathEnv = env.PATH || env.Path || '';
  const dirs = pathEnv.split(pathSeparator).map((d) => d.trim()).filter(Boolean);

  const filteredDirs = dirs.filter((dir) => {
    const norm = dir.replace(/\\/g, '/').toLowerCase();
    return !norm.includes('.agents/shims') && !norm.endsWith('/shims');
  });

  const gitExeNames = platform === 'win32' ? ['git.exe', 'git.cmd'] : ['git'];

  for (const dir of filteredDirs) {
    for (const exe of gitExeNames) {
      const candidate = path.join(dir, exe);
      try {
        if (fsModule.existsSync(candidate) && fsModule.statSync(candidate).isFile()) {
          return candidate;
        }
      } catch {
        // Continue searching
      }
    }
  }

  // System fallbacks when PATH does not resolve
  if (platform === 'win32') {
    const fallbacks = [
      'C:\\Program Files\\Git\\cmd\\git.exe',
      'C:\\Program Files\\Git\\bin\\git.exe',
      'C:\\Program Files (x86)\\Git\\cmd\\git.exe',
      'C:\\Program Files (x86)\\Git\\bin\\git.exe'
    ];
    for (const candidate of fallbacks) {
      if (fsModule.existsSync(candidate)) return candidate;
    }
  } else {
    const fallbacks = ['/usr/bin/git', '/usr/local/bin/git', '/opt/homebrew/bin/git'];
    for (const candidate of fallbacks) {
      if (fsModule.existsSync(candidate)) return candidate;
    }
  }

  return 'git';
}

/**
 * Returns the path to the bypass nonce file.
 */
export function getBypassNonceFilePath(workspaceDir = process.cwd()) {
  return path.join(workspaceDir, '.agents', 'cache', 'git_bypass_nonce.json');
}

/**
 * Returns the path to the security events log.
 */
export function getSecurityEventsFilePath(workspaceDir = process.cwd()) {
  return path.join(workspaceDir, '.agents', 'cache', 'security_events.jsonl');
}

/**
 * Generates a one-time cryptographic bypass nonce with a 60-second TTL.
 */
export function generateGitBypassNonce(workspaceDir = process.cwd(), ttlMs = DET19_CONSTANTS.BYPASS_NONCE_TTL_MS) {
  const nonce = crypto.randomBytes(16).toString('hex');
  const now = Date.now();
  const payload = {
    nonce,
    createdAtMs: now,
    expiresAtMs: now + ttlMs,
    createdAtIso: new Date(now).toISOString()
  };

  const noncePath = getBypassNonceFilePath(workspaceDir);
  fs.mkdirSync(path.dirname(noncePath), { recursive: true });
  fs.writeFileSync(noncePath, JSON.stringify(payload, null, 2), 'utf8');

  return payload;
}

/**
 * Consumes the one-time bypass nonce if present and unexpired.
 * Immediately unlinks the file to prevent replay attacks.
 */
export function consumeGitBypassNonce(workspaceDir = process.cwd()) {
  const noncePath = getBypassNonceFilePath(workspaceDir);
  if (!fs.existsSync(noncePath)) {
    return { allowed: false, reason: 'NO_NONCE' };
  }

  try {
    const raw = fs.readFileSync(noncePath, 'utf8');
    const data = JSON.parse(raw);
    const now = Date.now();

    // Invalidate immediately regardless of validity
    try {
      fs.unlinkSync(noncePath);
    } catch {
      // Ignore unlink errors
    }

    if (data.nonce && typeof data.expiresAtMs === 'number' && now <= data.expiresAtMs) {
      return { allowed: true, nonce: data.nonce };
    }

    return { allowed: false, reason: 'EXPIRED_NONCE' };
  } catch {
    try {
      fs.unlinkSync(noncePath);
    } catch {}
    return { allowed: false, reason: 'INVALID_NONCE' };
  }
}

/**
 * Records a security event in `.agents/cache/security_events.jsonl`.
 */
export function recordSecurityEvent(workspaceDir = process.cwd(), eventPayload = {}) {
  try {
    const eventsPath = getSecurityEventsFilePath(workspaceDir);
    fs.mkdirSync(path.dirname(eventsPath), { recursive: true });
    const line = JSON.stringify({
      timestamp: new Date().toISOString(),
      ...eventPayload
    }) + '\n';
    fs.appendFileSync(eventsPath, line, 'utf8');
  } catch {
    // Non-fatal telemetry failure
  }
}

/**
 * Inspects raw git CLI arguments and environment for DET-19 evasion patterns.
 */
export function inspectGitArgs(rawArgs = [], env = process.env) {
  // 1. Check hook-disabling environment variables
  if (String(env.HUSKY || '') === '0' || String(env.GIT_HOOKS || '') === '0') {
    return {
      blocked: true,
      detectorId: DET19_CONSTANTS.DETECTOR_ID,
      reason: 'Hook-disabling environment variable detected (HUSKY=0 or GIT_HOOKS=0)',
      subcommand: null,
      flags: ['HUSKY=0 / GIT_HOOKS=0']
    };
  }

  // 2. Parse global flags vs subcommand
  let subcommand = null;
  let subcommandIdx = -1;
  const globalFlags = [];
  const subcommandArgs = [];

  let i = 0;
  while (i < rawArgs.length) {
    const arg = rawArgs[i];
    if (arg === '--') {
      i++;
      continue;
    }

    if (subcommand === null) {
      if (arg.startsWith('-')) {
        globalFlags.push(arg);
        if (
          arg === '-c' ||
          arg === '-C' ||
          arg === '--git-dir' ||
          arg === '--work-tree' ||
          arg === '--namespace'
        ) {
          if (i + 1 < rawArgs.length) {
            globalFlags.push(rawArgs[i + 1]);
            i++;
          }
        }
      } else {
        subcommand = arg.toLowerCase();
        subcommandIdx = i;
        i++;
        break;
      }
    }
    i++;
  }

  if (subcommandIdx !== -1) {
    for (; i < rawArgs.length; i++) {
      subcommandArgs.push(rawArgs[i]);
    }
  }

  // 3. Inspect global flags for core.hooksPath overrides
  for (let j = 0; j < globalFlags.length; j++) {
    const gf = globalFlags[j];
    if (gf === '-c') {
      const nextVal = globalFlags[j + 1] || '';
      if (/^core\.hooksPath\s*=/i.test(nextVal)) {
        return {
          blocked: true,
          detectorId: DET19_CONSTANTS.DETECTOR_ID,
          subcommand,
          flags: ['-c', nextVal],
          reason: 'Global config override core.hooksPath is prohibited.'
        };
      }
    } else if (/^-c\s*core\.hooksPath\s*=/i.test(gf)) {
      return {
        blocked: true,
        detectorId: DET19_CONSTANTS.DETECTOR_ID,
        subcommand,
        flags: [gf],
        reason: 'Global config override core.hooksPath is prohibited.'
      };
    }
  }

  if (!subcommand) {
    return { blocked: false, subcommand: null, flags: [] };
  }

  // 4. Subcommand-specific bypass detection
  const blockedFlags = [];
  const VALUE_TAKING_LONG_FLAGS = new Set([
    '--message',
    '--file',
    '--author',
    '--date',
    '--template',
    '--cleanup',
    '--reuse-message',
    '--reedit-message',
    '--fixup',
    '--squash',
    '--trailer',
    '--pathspec-from-file',
    '--strategy',
    '--strategy-option',
    '--exec',
    '--onto'
  ]);
  if (DET19_CONSTANTS.PROTECTED_SUBCOMMANDS.includes(subcommand)) {
    for (let k = 0; k < subcommandArgs.length; k++) {
      const sArg = String(subcommandArgs[k] ?? '');
      if (sArg === '--') break;

      if (sArg === '--no-verify') {
        blockedFlags.push(sArg);
        continue;
      }

      if (VALUE_TAKING_LONG_FLAGS.has(sArg)) {
        // Skip the next token because it is the value for this option (e.g. --message "-next")
        k++;
        continue;
      }

      if (subcommand === 'commit') {
        if (sArg === '--no-gpg-sign') {
          blockedFlags.push(sArg);
        } else if (sArg === '-n') {
          blockedFlags.push(sArg);
        } else if (/^-[a-zA-Z]+$/.test(sArg)) {
          const cluster = sArg.slice(1);
          // If the flag cluster starts with a value-taking short option (-m, -F, -C, -c, -t) and has attached text,
          // only the first char is the option and the rest is its attached value (e.g., -mnext), unless it's pure flags like -amn / -anm.
          if (cluster.includes('n')) {
            blockedFlags.push(sArg);
          }
          // If any short flag in the cluster consumes the next argument (-m, -F, -C, -c, -t), advance k
          if (/[mFCct]/.test(cluster)) {
            k++;
          }
        }
      }
    }
  }

  if (blockedFlags.length > 0) {
    return {
      blocked: true,
      detectorId: DET19_CONSTANTS.DETECTOR_ID,
      subcommand,
      flags: blockedFlags,
      reason: `Pre-commit / verification bypass flags (${blockedFlags.join(', ')}) are prohibited for "git ${subcommand}".`
    };
  }

  return { blocked: false, subcommand, flags: [] };
}

/**
 * Runs the Git Guard engine for a CLI or process invocation.
 */
export function runGitGuard({
  args = process.argv.slice(2),
  env = process.env,
  cwd = process.cwd(),
  realGitBinary = null,
  spawnFn = spawnSync,
  stderr = process.stderr
} = {}) {
  const inspection = inspectGitArgs(args, env);

  if (inspection.blocked) {
    // Check for valid single-use human cryptographic nonce
    const nonceResult = consumeGitBypassNonce(cwd);
    if (nonceResult.allowed) {
      recordSecurityEvent(cwd, {
        event: 'DET-19_HOOK_BYPASS_AUTHORIZED_BY_NONCE',
        detectorId: DET19_CONSTANTS.DETECTOR_ID,
        subcommand: inspection.subcommand,
        flags: inspection.flags,
        cwd,
        nonce: nonceResult.nonce,
        blocked: false
      });
    } else {
      // Block execution
      if (stderr && typeof stderr.write === 'function') {
        stderr.write(`${DET19_CONSTANTS.BLOCKED_MESSAGE}\n`);
      }
      recordSecurityEvent(cwd, {
        event: 'DET-19_HOOK_BYPASS_ATTEMPT',
        detectorId: DET19_CONSTANTS.DETECTOR_ID,
        subcommand: inspection.subcommand,
        flags: inspection.flags,
        cwd,
        blocked: true,
        reason: inspection.reason
      });

      return {
        blocked: true,
        exitCode: DET19_CONSTANTS.EXIT_CODE_BLOCKED,
        reason: inspection.reason,
        inspection
      };
    }
  }

  // Execute real git binary
  const binary = realGitBinary || resolveRealGitBinary({ env });
  const child = spawnFn(binary, args, {
    cwd,
    env,
    stdio: 'inherit'
  });

  return {
    blocked: false,
    exitCode: child.status ?? 0
  };
}

// CLI Direct Invocation
const currentFilePath = fileURLToPath(import.meta.url);
const invokedFilePath = process.argv[1] ? path.resolve(process.argv[1]) : '';
if (invokedFilePath && path.resolve(currentFilePath) === invokedFilePath) {
  const result = runGitGuard();
  process.exit(result.exitCode);
}

export default {
  DET19_CONSTANTS,
  resolveRealGitBinary,
  getBypassNonceFilePath,
  getSecurityEventsFilePath,
  generateGitBypassNonce,
  consumeGitBypassNonce,
  recordSecurityEvent,
  inspectGitArgs,
  runGitGuard
};
